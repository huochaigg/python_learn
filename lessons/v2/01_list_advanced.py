"""V2-01 list 进阶：常用方法、原地修改 vs 返回新对象、切片。

学习目标：
1. 熟悉 list 增删改查常用方法。
2. 分清「修改原 list」和「返回新结果」。
3. 掌握切片语法，尤其是 [::-1]。

运行：uv run python lessons/v2/01_list_advanced.py
"""

nums: list[int] = [3, 1, 2, 1]
print("初始 nums =", nums)

# ---------------------------------------------------------------------------
# append：在末尾追加一个元素。参数：要追加的值。返回：None。会修改原 list。
# JS/TS 对比：≈ Array.push()
# ---------------------------------------------------------------------------
nums.append(4)
print("append(4) 之后 =", nums)

# ---------------------------------------------------------------------------
# insert：在指定下标插入。参数：index, value。返回：None。会修改原 list。
# JS/TS 对比：≈ splice(index, 0, value)；没有单独的 insert API。
# ---------------------------------------------------------------------------
nums.insert(0, 99)
print("insert(0, 99) 之后 =", nums)

# ---------------------------------------------------------------------------
# remove：按「值」删除第一次出现的元素。参数：要删的值。返回：None。会修改原 list。
# 注意：值不存在会抛 ValueError。只删第一个匹配项。
# JS/TS 对比：没有同名 API，常见写法是 splice(indexOf(x), 1)。
# ---------------------------------------------------------------------------
nums.remove(1)
print("remove(1) 之后（只删第一个 1）=", nums)

# ---------------------------------------------------------------------------
# pop：按「下标」取出并删除。参数：可选 index，默认最后一个。返回：被删的那个元素。
# 会修改原 list。
# JS/TS 对比：无参 pop() ≈ Array.pop()；pop(0) ≈ Array.shift()。
# ---------------------------------------------------------------------------
last = nums.pop()
print("pop() 取出末尾 =", last, "剩余 =", nums)
first = nums.pop(0)
print("pop(0) 取出下标 0 =", first, "剩余 =", nums)

# ---------------------------------------------------------------------------
# index：返回某值第一次出现的下标。参数：value。返回：int。不修改原 list。
# 注意：找不到会抛 ValueError（JS 的 indexOf 找不到返回 -1）。
# JS/TS 对比：≈ Array.indexOf()，但失败行为不同。
# ---------------------------------------------------------------------------
found_at = nums.index(2)
print("index(2) =", found_at)

# ---------------------------------------------------------------------------
# count：统计某值出现次数。参数：value。返回：int。不修改原 list。
# JS/TS 对比：没有内置，通常 filter(x => x === v).length。
# ---------------------------------------------------------------------------
print("count(1) =", nums.count(1), "当前 nums =", nums)

# ---------------------------------------------------------------------------
# sort：原地排序。参数：可选 key、reverse。返回：None。会修改原 list。
# JS/TS 对比：Array.sort() 同样会改原数组。
# ---------------------------------------------------------------------------
to_sort = [3, 1, 4, 1, 5]
to_sort.sort()
print("sort() 之后原 list =", to_sort)
to_sort.sort(reverse=True)
print("sort(reverse=True) 之后 =", to_sort)

# ---------------------------------------------------------------------------
# sorted：返回排好序的新 list。参数：可迭代对象。返回：新 list。不修改原对象。
# JS/TS 对比：更接近 [...arr].sort() 或较新的 Array.toSorted()。
# 注意：sort() 改原对象；sorted() 拿副本。日常更推荐 sorted()，副作用更少。
# ---------------------------------------------------------------------------
original = [3, 1, 4]
new_list = sorted(original)
print("sorted 原对象仍是", original, "新 list =", new_list)

# ---------------------------------------------------------------------------
# reverse：原地倒序。无参。返回：None。会修改原 list。
# JS/TS 对比：≈ Array.reverse()（同样改原数组）。
# ---------------------------------------------------------------------------
to_reverse = [1, 2, 3]
to_reverse.reverse()
print("reverse() 之后原 list =", to_reverse)

# ---------------------------------------------------------------------------
# reversed：返回倒序迭代器，不是 list。不修改原对象。
# 注意：打印时通常包一层 list()。它是惰性的，不是立刻生成新数组。
# JS/TS 对比：更接近 [...arr].reverse() / Array.toReversed()，但返回的是迭代器。
# ---------------------------------------------------------------------------
source = [1, 2, 3]
print("reversed 转 list =", list(reversed(source)), "原对象仍是", source)

# ---------------------------------------------------------------------------
# 切片：list[start:end:step]
# - start 含，end 不含（和 JS slice 一样）
# - 缺省 start=0，end=len，step=1
# - [::-1] 从后往前，得到反转后的新 list，不改原对象
# JS/TS 对比：≈ Array.slice()；没有 step。反转常用 toReversed() 或 [...arr].reverse()。
# ---------------------------------------------------------------------------
letters = ["a", "b", "c", "d", "e"]
print("letters[1:4] =", letters[1:4])
print("letters[:3]  =", letters[:3])
print("letters[2:]  =", letters[2:])
print("letters[::2] =", letters[::2])
print("letters[::-1] =", letters[::-1], "原对象仍是", letters)

if __name__ == "__main__":
    print("\n--- 01 list 进阶 运行完毕 ---")

# 本文件重点：
# 1. append / insert / remove / pop 都会改原 list。
# 2. sort / reverse 改原对象；sorted / reversed / 切片返回新结果。
# 3. index 找不到会抛错，不像 JS indexOf 返回 -1。
# 4. [::-1] 是最常见的「得到反转副本」写法。
