"""V2-03 set 进阶：去重、增删、成员判断、集合运算。

学习目标：
1. 理解 set 自动去重、无序。
2. 分清 remove 和 discard。
3. 会用 | & - 以及 list ↔ set 转换。
4. 用交集做简单权限判断。

运行：uv run python lessons/v2/03_set_advanced.py
"""

# ---------------------------------------------------------------------------
# set：无序、元素不重复。字面量用 {}，但空集合必须写 set()，因为 {} 是空 dict。
# JS/TS 对比：≈ new Set(...)
# 注意：set 没有下标，不能 tags[0]。
# ---------------------------------------------------------------------------
tags = {"python", "backend", "python"}
print("自动去重 tags =", tags)

# ---------------------------------------------------------------------------
# add：加入一个元素。参数：value。返回：None。会修改原 set。
# 已存在则什么也不做（不会报错，也不会重复）。
# JS/TS 对比：≈ set.add(value)
# ---------------------------------------------------------------------------
tags.add("fastapi")
print("add('fastapi') 之后 =", tags)

# ---------------------------------------------------------------------------
# remove：删除元素。参数：value。返回：None。会修改原 set。
# 注意：元素不存在 → KeyError。
# discard：同样删除；不存在时安静跳过，不报错。
# JS/TS 对比：Set.delete() 不存在也返回 false，更接近 discard。
# ---------------------------------------------------------------------------
tags.discard("not-exist")
print("discard 不存在的元素，不报错 =", tags)
tags.remove("backend")
print("remove('backend') 之后 =", tags)

# ---------------------------------------------------------------------------
# in：判断成员。返回 bool。不修改原对象。
# JS/TS 对比：≈ set.has(x)；数组里常用 includes。
# ---------------------------------------------------------------------------
print("'python' in tags =", "python" in tags)
print("'backend' in tags =", "backend" in tags)

# ---------------------------------------------------------------------------
# 并集 |  交集 &  差集 -
# 这些运算返回新 set，不修改原对象。
# JS/TS 对比：较新的 Set.union / intersection / difference；老写法要自己循环。
# ---------------------------------------------------------------------------
a = {1, 2, 3}
b = {3, 4}
print("a | b 并集 =", a | b)
print("a & b 交集 =", a & b)
print("a - b 差集（在 a 不在 b）=", a - b)
print("运算后原 a, b 不变：", a, b)

# ---------------------------------------------------------------------------
# list → set 去重，再转回 list
# JS/TS 对比：≈ [...new Set(array)]
# 注意：set 无序，转回 list 后顺序不一定和原来一样。
# ---------------------------------------------------------------------------
raw = [3, 1, 2, 1, 3]
unique = set(raw)
print("list 转 set 去重 =", unique)
print("set 再转 list =", list(unique))

# ---------------------------------------------------------------------------
# 权限例子：用交集判断是否拥有所需角色
# 思路：user_roles ∩ required_roles 非空，就说明至少命中一个所需角色。
# ---------------------------------------------------------------------------
user_roles = {"admin", "editor"}
required_roles = {"admin"}
has_permission = bool(user_roles & required_roles)
print("user_roles =", user_roles)
print("required_roles =", required_roles)
print("是否拥有所需权限 =", has_permission)

# 后续 FastAPI 中会经常出现：用 set 做角色/权限去重和交集判断。

if __name__ == "__main__":
    print("\n--- 03 set 进阶 运行完毕 ---")

