"""V3-01 位置参数与关键字参数。

学习目标：
1. 分清按位置传参和按关键字传参。
2. 理解 Python 里「参数名本身也是调用协议的一部分」。
3. 知道混合调用时的限制：关键字参数后面不能再跟位置参数。

运行：uv run python lessons/v3/01_function_arguments.py
"""


def create_user(name: str, age: int) -> str:
    """按名字和年龄拼一句描述。

    参数：
        name: 用户名
        age: 年龄
    返回：
        一段字符串，不修改外部状态。
    """
    return f"{name} is {age}"


# ---------------------------------------------------------------------------
# 位置参数：按定义顺序传，不写参数名。
# JS/TS 对比：createUser("Tom", 31) 就是这种。
# ---------------------------------------------------------------------------
by_position = create_user("Tom", 31)
print("位置参数 =", by_position)

# ---------------------------------------------------------------------------
# 关键字参数：调用时显式写出参数名。
# JS/TS 对比：JS 没有「按参数名传」的语言级语法，通常改成传一个对象：
#   createUser({ name: "Tom", age: 31 })
# Python 可以直接：create_user(name="Tom", age=31)
# 后续 FastAPI / LangChain 中会经常出现：ChatOpenAI(model="xxx", temperature=0)
# ---------------------------------------------------------------------------
by_keyword = create_user(name="Tom", age=31)
print("关键字参数 =", by_keyword)

# 关键字参数可以换顺序，只要名字对得上。
swapped = create_user(age=31, name="Tom")
print("关键字换序 =", swapped)

# ---------------------------------------------------------------------------
# 混合调用：前面用位置，后面用关键字。很常见。
# 注意：一旦开始写关键字，后面就不能再写纯位置参数。
#   create_user("Tom", age=31)     合法
#   create_user(name="Tom", 31)    语法错误
# JS/TS 对比：JS 没有这套规则，因为它本来就不能按参数名传。
# ---------------------------------------------------------------------------
mixed = create_user("Tom", age=31)
print("混合调用 =", mixed)

if __name__ == "__main__":
    print("\n--- 01 函数参数 运行完毕 ---")

# 本文件重点：
# 1. create_user("Tom", 31) 是位置参数；create_user(name="Tom", age=31) 是关键字参数。
# 2. Python 的参数名是调用协议的一部分，库 API 大量依赖关键字参数。
# 3. 混合调用时，关键字后面不能再跟位置参数。
# 4. 和 JS「传一个 options 对象」是同一类可读性需求，但 Python 是语言内置能力。
