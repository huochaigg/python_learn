"""被 06 导入的小模块：用来对比「直接运行」和「被 import」。"""

print("greeter.py 正在加载，此时 __name__ =", __name__)


def greet(name: str) -> str:
    """返回一句问候。"""
    return f"Hello, {name}"


def main() -> None:
    """只有作为程序入口时才应该跑的演示逻辑。"""
    print("greeter.main() 被调用")
    print(greet("Ada"))


# ---------------------------------------------------------------------------
# if __name__ == "__main__":
# __name__ 是什么：每个模块都有的特殊变量，表示「当前模块叫什么」。
# __main__ 是什么：当前文件正作为程序入口被直接执行。
# 什么时候用：这个文件既要能被 import 复用，又要能单独跑一下看看效果。
# 坑：如果把 main() 直接写在文件底下一律执行，别人 import greeter 也会跑起来。
# JS/TS 对比：思路类似「判断当前文件是不是入口」；Node 的机制不同，不要一一对应。
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    main()
